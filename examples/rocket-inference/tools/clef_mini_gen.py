"""Generates src/clef/model/mini_expected.in: the expected output of a tiny 2-layer
Clef-style MoE decoder (hidden 64, 4 heads / 2 kv, head_dim 16, 4 experts top-2,
inter 32) computed with `manual_layer` of clef_reference.py. The weights follow the
closed formula in `val()` (mirrored by src/clef/model/tests.rs), so no files are needed.

    /home/royalcat/models/venvs/clef/bin/python -I tools/clef_mini_gen.py <out.in>
"""
import importlib.util, math, sys
from pathlib import Path
from types import SimpleNamespace
import numpy as np
import torch

here = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("clef_reference", here / "clef_reference.py")
ref = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ref)

H, NH, NKV, D, E, K, I, S, L = 64, 4, 2, 16, 4, 2, 32, 5, 2


def val(n, salt, scale=0.2):
    i = np.arange(n, dtype=np.float64)
    return torch.tensor(np.sin(i * 0.37 + salt) * scale, dtype=torch.float32)


def tensor(shape, salt, scale=0.2):
    n = int(np.prod(shape))
    return val(n, salt, scale).view(*shape)


def layer_tensors(l):
    s = 10.0 * l
    t = {
        "input_layernorm.weight": 1 + tensor([H], s + 1, 0.1),
        "post_attention_layernorm.weight": 1 + tensor([H], s + 2, 0.1),
        "self_attn.q_proj.weight": tensor([NH * D, H], s + 3, 0.3),
        "self_attn.k_proj.weight": tensor([NKV * D, H], s + 4, 0.3),
        "self_attn.v_proj.weight": tensor([NKV * D, H], s + 5, 0.3),
        "self_attn.o_proj.weight": tensor([H, NH * D], s + 6, 0.3),
        "self_attn.q_norm.weight": 1 + tensor([D], s + 7, 0.1),
        "self_attn.k_norm.weight": 1 + tensor([D], s + 8, 0.1),
        "mlp.gate.weight": tensor([E, H], s + 9, 0.5),
    }
    gu = [torch.cat([tensor([I, H], s + 20 + e, 0.3), tensor([I, H], s + 30 + e, 0.3)], 0) for e in range(E)]
    t["mlp.experts.gate_up_proj"] = torch.stack(gu)
    t["mlp.experts.down_proj"] = torch.stack([tensor([H, I], s + 40 + e, 0.3) for e in range(E)])
    return t


tc = SimpleNamespace(
    hidden_size=H, num_attention_heads=NH, num_key_value_heads=NKV, head_dim=D, rms_norm_eps=1e-6,
    rope_theta=1e6, num_experts=E, num_experts_per_tok=K, moe_intermediate_size=I, norm_topk_prob=True,
)
x = tensor([S, H], 99.0, 1.0)
out, ids, ws = [], [], []
with torch.inference_mode():
    for l in range(L):
        x, idx, w = ref.manual_layer(x, layer_tensors(l), tc, return_routing=True)
        out.append(x.clone()); ids.append(idx); ws.append(w)


def arr(name, ty, a):
    return f"pub const {name}: [{ty}; {len(a)}] = [{', '.join(np.format_float_positional(np.float32(v), unique=True, trim='-') if ty == 'f32' else str(int(v)) for v in a)}];\n"


with open(sys.argv[1], "w") as f:
    f.write("// generated by tools/clef_mini_gen.py (torch manual_layer); do not edit\n")
    for l in range(L):
        f.write(arr(f"HIDDEN_L{l}", "f32", out[l].flatten().tolist()))
        f.write(arr(f"IDS_L{l}", "u32", ids[l].flatten().tolist()))
        f.write(arr(f"WTS_L{l}", "f32", ws[l].flatten().tolist()))
print("ok", float(out[-1].abs().max()))
